import http.server
import socketserver
import os
import json
import urllib.request
import urllib.error

PORT = 8000
DIRECTORY = os.path.join(os.path.dirname(os.path.abspath(__file__)), "app")
GEMINI_API_KEY = os.environ.get("GEMINI_API_KEY", "{YOUR_API_KEY}")
GEMINI_MODEL = "gemini-2.5-flash"

# Load mock schema for token-efficient grounding
DATA_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "data")
try:
    with open(os.path.join(DATA_DIR, "mock_schema.json"), "r", encoding="utf-8") as f:
        SCHEMA_CONTEXT = json.dumps(json.load(f))
except Exception:
    SCHEMA_CONTEXT = "{}"

def call_gemini(prompt: str, system_instruction: str = "", max_tokens: int = 1500) -> str:
    url = f"https://generativelanguage.googleapis.com/v1beta/models/{GEMINI_MODEL}:generateContent?key={GEMINI_API_KEY}"
    
    payload = {
        "contents": [
            {
                "role": "user",
                "parts": [{"text": prompt}]
            }
        ],
        "generationConfig": {
            "temperature": 0.2,
            "maxOutputTokens": max_tokens,
            "thinkingConfig": {"thinkingBudget": 0}
        }
    }
    
    if system_instruction:
        payload["systemInstruction"] = {
            "parts": [{"text": system_instruction}]
        }

    req = urllib.request.Request(
        url,
        data=json.dumps(payload).encode("utf-8"),
        headers={"Content-Type": "application/json"}
    )
    
    with urllib.request.urlopen(req, timeout=30) as resp:
        result = json.loads(resp.read().decode("utf-8"))
        candidates = result.get("candidates", [])
        if candidates and "content" in candidates[0]:
            parts = candidates[0]["content"].get("parts", [])
            if parts:
                return parts[0].get("text", "")
        return "No response generated by model."

class StudioRequestHandler(http.server.SimpleHTTPRequestHandler):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, directory=DIRECTORY, **kwargs)

    def do_POST(self):
        if self.path == "/api/generate":
            content_length = int(self.headers.get("Content-Length", 0))
            body = self.rfile.read(content_length)
            try:
                data = json.loads(body.decode("utf-8"))
                action = data.get("action", "custom")
                user_prompt = data.get("prompt", "")
                system_prompt = data.get("systemPrompt", "")
                
                # Token-optimized context injection
                if action == "planning_ambiguity":
                    sys_inst = (
                        "You are the Salesforce Solution Planning Agent. "
                        f"Grounded Schema Context: {SCHEMA_CONTEXT}. "
                        "Detect requirement ambiguities, missing fields, or unclear logic. Output 3 concise numbered questions."
                    )
                    out = call_gemini(user_prompt, sys_inst, max_tokens=400)

                elif action == "planning_solution":
                    sys_inst = (
                        "You are the Salesforce Solution Planning Agent. "
                        f"Grounded Schema Context: {SCHEMA_CONTEXT}. "
                        "Produce a structured Salesforce technical plan with: "
                        "1. Architecture Strategy (Declarative/Programmatic/Hybrid with trade-off reason), "
                        "2. Component Impact Matrix, 3. Step-by-Step Build Checklist, 4. Test Scenarios (Bulk 200/Positive/Negative), 5. Governor Limit & OWASP Risk Review."
                    )
                    out = call_gemini(user_prompt, sys_inst, max_tokens=1500)

                elif action == "refactor_apex":
                    sys_inst = (
                        "You are the Salesforce AI Coding Assistant. "
                        f"Grounded Schema Context: {SCHEMA_CONTEXT}. "
                        "Refactor the provided Apex code strictly enforcing: "
                        "1. Bulkification (NO SOQL/DML in loops, Map pattern), "
                        "2. 'with sharing' or 'inherited sharing', "
                        "3. 'WITH USER_MODE' on queries and AccessLevel.USER_MODE on Database methods, "
                        "4. Exception handling. Return clean Apex code with comments."
                    )
                    out = call_gemini(user_prompt, sys_inst, max_tokens=1400)

                elif action == "generate_test":
                    sys_inst = (
                        "You are the Salesforce AI Coding Assistant. "
                        "Generate a complete enterprise Apex test class for the given code. "
                        "Include @isTest, @TestSetup, Test.startTest()/stopTest(), positive test, negative test, and 200-record bulk test using System.Assert."
                    )
                    out = call_gemini(user_prompt, sys_inst, max_tokens=1200)

                elif action == "soql_optimize":
                    sys_inst = (
                        "You are the Salesforce SOQL Optimization Expert. "
                        f"Grounded Schema Context: {SCHEMA_CONTEXT}. "
                        "Analyze and optimize the given SOQL query for index selectivity, relationship traversal, and WITH USER_MODE. Provide the query and concise metric explanation."
                    )
                    out = call_gemini(user_prompt, sys_inst, max_tokens=800)

                else:
                    out = call_gemini(user_prompt, system_prompt or "You are an expert Salesforce Developer AI.", max_tokens=1000)

                response_payload = {"success": True, "result": out}
            except Exception as e:
                response_payload = {"success": False, "error": str(e)}

            self.send_response(200)
            self.send_header("Content-Type", "application/json")
            self.send_header("Access-Control-Allow-Origin", "*")
            self.end_headers()
            self.wfile.write(json.dumps(response_payload).encode("utf-8"))

        elif self.path == "/api/audit":
            # Real-time Static + AI combined audit
            content_length = int(self.headers.get("Content-Length", 0))
            body = self.rfile.read(content_length)
            try:
                data = json.loads(body.decode("utf-8"))
                code = data.get("code", "")
                
                from engine.rules_engine import SalesforceRulesEngine
                engine = SalesforceRulesEngine()
                static_res = engine.analyze_apex(code)
                
                # Optional quick LLM insight
                llm_prompt = f"Review this Apex code snippet for governor limit safety and security in 3 bullet points:\n{code}"
                llm_review = call_gemini(llm_prompt, "You are a Salesforce Security Architect.", max_tokens=300)
                
                response_payload = {
                    "success": True,
                    "staticAudit": static_res,
                    "aiInsight": llm_review
                }
            except Exception as e:
                response_payload = {"success": False, "error": str(e)}

            self.send_response(200)
            self.send_header("Content-Type", "application/json")
            self.send_header("Access-Control-Allow-Origin", "*")
            self.end_headers()
            self.wfile.write(json.dumps(response_payload).encode("utf-8"))
        else:
            self.send_error(404, "Endpoint not found")

    def do_OPTIONS(self):
        self.send_response(200)
        self.send_header("Access-Control-Allow-Origin", "*")
        self.send_header("Access-Control-Allow-Methods", "POST, GET, OPTIONS")
        self.send_header("Access-Control-Allow-Headers", "Content-Type")
        self.end_headers()

if __name__ == "__main__":
    print(f"Starting Live AI Salesforce Studio Server on http://localhost:{PORT}")
    with socketserver.TCPServer(("", PORT), StudioRequestHandler) as httpd:
        try:
            httpd.serve_forever()
        except KeyboardInterrupt:
            print("\nShutting down server.")
